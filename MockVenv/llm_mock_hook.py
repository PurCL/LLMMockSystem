_recent_mock_calls = []

def _get_logical_signature(name, args=None, kwargs=None):
    """Generate logical signature: e.g., 'jwt.decode(...)'"""
    if args is None and kwargs is None:
        return name 
    
    arg_reprs = [repr(a)[:50] for a in (args or [])]
    kwarg_reprs = [f"{k}={repr(v)[:50]}" for k, v in (kwargs or {}).items()]
    signature = f"{name}({', '.join(arg_reprs + kwarg_reprs)})"
    return signature

def _track_and_get_mock(sig_key, args=None, kwargs=None):
    _recent_mock_calls.append(sig_key)
    if len(_recent_mock_calls) > 100:
        _recent_mock_calls.pop(0)

    root_pkg = sig_key.split('.')[0].split('(')[0]
    res = mock_state.get("mocked_imports", {}).get(root_pkg, {}).get("api_features", {})

    def _extract_return(feature_data):
        if isinstance(feature_data, dict) and "return_value" in feature_data:
            return feature_data["return_value"]
        # If return_value is missing, return None (allow APIs with no return value)
        return None

    def _match_parameters(stored_params, call_args, call_kwargs):
        """Match parameters based on stored parameter values"""
        if not isinstance(stored_params, dict):
            return True  # No parameters to match, accept any call

        stored_args = stored_params.get("args", [])
        stored_kwargs = stored_params.get("kwargs", {})

        # Check if both stored and call have no parameters (empty parameters case)
        if not stored_args and not stored_kwargs:
            # Empty parameters should only match empty calls
            return not call_args and not call_kwargs

        # Match args
        if stored_args:
            if not call_args or len(call_args) != len(stored_args):
                return False
            for i, (stored_arg, call_arg) in enumerate(zip(stored_args, call_args)):
                # Convert both to string for comparison
                if str(stored_arg) != str(repr(call_arg)[:150]):
                    return False

        # Match kwargs
        if stored_kwargs:
            if not call_kwargs:
                return False
            for key, stored_value in stored_kwargs.items():
                if key not in call_kwargs:
                    return False
                if str(stored_value) != str(repr(call_kwargs[key])[:150]):
                    return False

        return True

    def _search_in_parameters_list(parameters_list, call_args, call_kwargs):
        """Search through the list of parameter configurations to find a match"""
        if not isinstance(parameters_list, list):
            return None

        for param_config in parameters_list:
            if _match_parameters(param_config, call_args, call_kwargs):
                return param_config

        return None

    # Extract API name (without parentheses and parameters)
    base_name = sig_key.split('(')[0]

    # Try to match by API name and parameters
    if base_name in res:
        api_data = res[base_name]
        if isinstance(api_data, dict):
            if "parameters" in api_data:
                # Search through the list for a matching parameter configuration
                matched_config = _search_in_parameters_list(api_data["parameters"], args or [], kwargs or {})
                if matched_config:
                    # Return tuple: (found, return_value)
                    return (True, matched_config.get("return_value"))
                else:
                    # API found but no matching parameters - return (False, None) to trigger LLM
                    return (False, None)
            else:
                # No parameters stored, return the mock (backward compatibility)
                return (True, _extract_return(api_data))

    # Fallback: try method name only
    api_name = base_name.split('.')[-1]
    if api_name in res:
        api_data = res[api_name]
        if isinstance(api_data, dict):
            if "parameters" in api_data:
                matched_config = _search_in_parameters_list(api_data["parameters"], args or [], kwargs or {})
                if matched_config:
                    return (True, matched_config.get("return_value"))
                else:
                    return (False, None)
            else:
                return (True, _extract_return(api_data))

    # API not found in mock_state
    return (False, None)

