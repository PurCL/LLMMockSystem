class LLMMockProxyMeta(type):
    def __instancecheck__(cls, instance): return True
    def __subclasscheck__(cls, subclass): return True

class LLMMockProxy(metaclass=LLMMockProxyMeta):
    def __init__(self, name, *args, **kwargs):
        object.__setattr__(self, '_name', name)
        object.__setattr__(self, '__bases__', (object,))
        object.__setattr__(self, '__mro__', (self, object))

    def __mro_entries__(self, bases):
        def mock_init_subclass(cls, **kwargs): pass
        mock_base = type(self._name, (object,), {
            '__module__': '__main__',
            '__qualname__': self._name,
            '__init_subclass__': classmethod(mock_init_subclass),
        })
        return (mock_base,)

    def __getattr__(self, item):
        if item in ('_name', '__bases__', '__mro__'):
            return object.__getattribute__(self, item)
        if item in ('__path__', '__file__', '__spec__'):
            raise AttributeError(item)
        if item == '__name__':
            return self._name
        if item == '__class__':
            return type(self._name, (object,), {})

        full_path = f"{self._name}.{item}"
        sig_key = _get_logical_signature(full_path)

        # Look for explicit attribute mock (e.g., constants)
        found, mock_val = _track_and_get_mock(sig_key, None, None)
        if found:
            return mock_val

        if "Error" in item or "Exception" in item:
            class MockException(Exception): pass
            MockException.__name__ = item
            return MockException

        if item.startswith('__') and item.endswith('__'):
            raise AttributeError(item)

        # Return proxy to allow chaining (e.g., module.submodule.func())
        # The halt will happen in __call__ if the user actually invokes it.
        return LLMMockProxy(full_path)

    def __setattr__(self, name, value):
        if name in ('_name', '__bases__', '__mro__'):
            object.__setattr__(self, name, value)
        pass

    def __call__(self, *args, **kwargs):
        sig_key = _get_logical_signature(self._name, args, kwargs)
        found, mock_val = _track_and_get_mock(sig_key, args, kwargs)

        # 1. API found in mock_state: return the recorded value (even if it's None)
        if found:
            print(f"✅ [Mock Hit] API '{self._name}' found in mock_state, returning: {repr(mock_val)[:100]}")
            return mock_val

        # 2. API NOT found in mock_state: need to prompt LLM
        print(f"⚠️ [Mock Miss] API '{self._name}' not found in mock_state, consulting LLM...")

        def _safe_repr(val, max_len=150):
            try:
                r = repr(val)
                if len(r) > max_len:
                    return r[:max_len//2] + "..." + r[-max_len//2:]
                return r
            except Exception:
                return "<Unrepresentable Object>"

        call_details = {
            "api_path": str(self._name),
            "signature": str(sig_key),
            "args": [_safe_repr(a) for a in args],
            "kwargs": {str(k): _safe_repr(v) for k, v in kwargs.items()}
        }

        # FAIL FAST: API lacks mock data. Halt execution immediately!
        print(f"\n" + "🔥"*25)
        print(f"🚨 [Origin Intercept] API '{self._name}' called but lacks mock data.")
        print(f"📦 Arguments intercepted: args={call_details['args']}, kwargs={call_details['kwargs']}")
        print(f"🛑 Halting execution and consulting LLM Agent...")
        print("🔥"*25 + "\n")

        # Capture the current stack trace omitting this immediate function call
        tb_list = traceback.format_stack()[:-1]
        tb_str = "".join(tb_list)

        error_msg = (
            f"MockMissingError: Execution halted at '{sig_key}'. The mock engine requires a return value for this API call to proceed.\n\n"
            f"Full Arguments intercepted:\n{json.dumps(call_details, indent=2)}\n\n"
            f"⚠️ TASK: You MUST generate a JSON patch to mock this API.\n"
            f"For the API ('{sig_key}'), provide ONLY:\n"
            f"1. 'description' (what the API does)\n"
            f"2. 'return_value' (the mocked output required to bypass this failure and satisfy the business logic).\n\n"
            f"Expected JSON Format:\n"
            f"{{\n"
            f"  \"description\": \"...\",\n"
            f"  \"return_value\": ...\n"
            f"}}\n\n"
            f"Stack Trace:\n{tb_str}"
        )

        try:
            import llm_client
            patch = llm_client.API_feature(error_msg, _recent_mock_calls)
            if patch and "return_value" in patch:
                # Extract API name without parentheses and parameters
                api_name = self._name
                # Always record parameters, even if empty (to distinguish no-param calls from other calls)
                # The new format will be handled by _update_state_and_save to append to parameters list
                wrapped_patch = {
                    "api_features": {
                        api_name: {
                            "description": patch.get("description", "Auto-generated mock by LLM"),
                            "parameters": {
                                "args": call_details["args"] if call_details["args"] else [],
                                "kwargs": call_details["kwargs"] if call_details["kwargs"] else {}
                            },
                            "return_value": patch["return_value"]
                        }
                    }
                }
                _update_state_and_save(wrapped_patch)

                # Check if this is adding a new parameter configuration to an existing API
                root_pkg = api_name.split('.')[0].split('(')[0]
                existing_api = mock_state.get("mocked_imports", {}).get(root_pkg, {}).get("api_features", {}).get(api_name)
                if existing_api and "parameters" in existing_api and isinstance(existing_api["parameters"], list):
                    param_count = len(existing_api["parameters"])
                    print(f"✅ [LLM Mock] New parameter configuration added! API '{api_name}' now has {param_count} parameter configurations.")
                else:
                    print(f"✅ [LLM Mock] First parameter configuration created for API '{api_name}'.")

                print("🛑 [LLM Mock] Patch applied! Forcefully terminating process. Please restart.")
            else:
                print("❌ [Fix Failed] Agent failed to generate a valid remediation patch (missing 'return_value').")
        except Exception as ex:
            print(f"⚠️ [System Error]: {ex}")

        # Suicide to allow external script/harness to restart with new state
        import os
        os._exit(1)

    def __iter__(self):
        yield LLMMockProxy(f"{self._name}_item")

    def __getitem__(self, key):
        sig_key = f"{self._name}[{repr(key)}]"
        found, mock_val = _track_and_get_mock(sig_key, None, None)
        if found:
            return mock_val
        # If subscript access lacks data, we can also halt here if needed
        return LLMMockProxy(sig_key)

    def __len__(self): return 1
    def __bool__(self): return True
    def __str__(self): return ""
    def __repr__(self): return self._name

class GhostModule(types.ModuleType):
    def __getattr__(self, name):
        full_path = f"{self.__name__}.{name}"
        sig_key = _get_logical_signature(full_path)

        found, mock_val = _track_and_get_mock(sig_key, None, None)
        if found:
            return mock_val

        if "Error" in name or "Exception" in name:
            class MockException(Exception): pass
            MockException.__name__ = name
            return MockException

        if name.startswith('__') and name.endswith('__'):
            raise AttributeError(name)

        return LLMMockProxy(full_path)

class GhostLoader:
    def __init__(self, fullname): self.fullname = fullname
    def create_module(self, spec):
        import sys as _sys; _sys.stderr.write(f"[DEBUG] create_module called for {self.fullname}\n"); _sys.stderr.flush()
        mod = GhostModule(self.fullname)
        mod.__path__ = []
        return mod
    def exec_module(self, module):
        import sys as _sys; _sys.stderr.write(f"[DEBUG] exec_module called for {module.__name__}\n"); _sys.stderr.flush()
        module.__dict__.update({'__path__': []})


class GhostFinder:
    def find_spec(self, fullname, path, target=None):
        # 1. Filter out built-in and private modules
        if fullname.startswith('_') or fullname in sys.builtin_module_names:
            return None

        base_name = fullname.split('.')[0]

        if hasattr(sys, 'stdlib_module_names') and base_name in sys.stdlib_module_names:
            return None

        # 2. Filter out blacklisted modules (e.g., underlying framework modules)
        if base_name in IGNORED_MODULES:
            return None

        # ==================== Mock Mode Logic ====================
        # Reaching this point means the standard PathFinder has already failed.
        # Therefore, the package is definitely NOT installed in the environment.

        # 3. Check if the package is in the requirements whitelist (ALLOWED_MOCKS)
        if ALLOWED_MOCKS:
            # First check direct match
            if base_name in ALLOWED_MOCKS:
                print(f"[⚙️ Ghost Engine] Auto-pretending successful import of uninstalled package: '{fullname}'")
                _record_mocked_import(fullname)
                return ModuleSpec(fullname, GhostLoader(fullname))

            # If not found, try to resolve using the mapping file
            # Check if any package in REQUIRED_PACKAGES resolves to this import name
            for req_pkg in REQUIRED_PACKAGES:
                resolved_import = _resolve_import_name(req_pkg)
                if resolved_import == base_name:
                    print(f"[⚙️ Ghost Engine] Resolved '{fullname}' as import name for PyPI package '{req_pkg}'")
                    print(f"[⚙️ Ghost Engine] Auto-pretending successful import of uninstalled package: '{fullname}'")
                    _record_mocked_import(fullname)
                    return ModuleSpec(fullname, GhostLoader(fullname))

            # Not in the whitelist and no mapping found: do not intercept.
            # Return None to let the system naturally raise a ModuleNotFoundError.
            return None

