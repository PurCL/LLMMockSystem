_recent_mock_calls = []

def _get_logical_signature(name, args=None, kwargs=None):
    """Generate logical signature: e.g., 'jwt.decode(...)'"""
    if args is None and kwargs is None:
        return name 
    
    arg_reprs = [repr(a)[:50] for a in (args or [])]
    kwarg_reprs = [f"{k}={repr(v)[:50]}" for k, v in (kwargs or {}).items()]
    signature = f"{name}({', '.join(arg_reprs + kwarg_reprs)})"
    return signature

def _track_and_get_mock(sig_key):
    _recent_mock_calls.append(sig_key)
    if len(_recent_mock_calls) > 100: 
        _recent_mock_calls.pop(0)

    root_pkg = sig_key.split('.')[0].split('(')[0]
    res = mock_state.get("mocked_imports", {}).get(root_pkg, {}).get("api_features", {})
    
    def _extract_return(feature_data):
        if isinstance(feature_data, dict) and "return_value" in feature_data:
            return feature_data["return_value"]
        return feature_data

    # 1. Full logical signature match
    if sig_key in res: 
        return _extract_return(res[sig_key])
        
    # 2. Downgrade match: Base API path
    base_name = sig_key.split('(')[0]
    if base_name in res: 
        return _extract_return(res[base_name])
    if f"{base_name}()" in res: 
        return _extract_return(res[f"{base_name}()"])
        
    # 3. Ultimate downgrade: Method name only
    api_name = base_name.split('.')[-1]
    if api_name in res:
        return _extract_return(res[api_name])
    if f"{api_name}()" in res:
        return _extract_return(res[f"{api_name}()"])
            
    return None

