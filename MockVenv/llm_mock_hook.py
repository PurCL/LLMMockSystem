def _update_state_and_save(patch):
    """Receive patch from LLM and distribute it to the corresponding Package's territory"""
    print(f"✨ [Fix Successful] Patch generated by LLM: {patch}")

    if "env" in patch:
        mock_state.setdefault("env", {}).update(patch["env"])

    if "api_features" in patch:
        for sig_key, feature_dict in patch["api_features"].items():
            root_pkg = sig_key.split('.')[0].split('(')[0]
            pkg_entry = mock_state.setdefault("mocked_imports", {}).setdefault(root_pkg, {})
            api_dict = pkg_entry.setdefault("api_features", {})

            # Handle the new parameter list format
            if sig_key in api_dict and isinstance(api_dict[sig_key], dict):
                existing_api = api_dict[sig_key]

                # If the existing API has a parameters field
                if "parameters" in existing_api:
                    # Convert old single-parameter format to list format if needed
                    if not isinstance(existing_api["parameters"], list):
                        existing_api["parameters"] = [existing_api["parameters"]]

                    # Add new parameter configuration to the list
                    if "parameters" in feature_dict:
                        new_param_config = feature_dict["parameters"]
                        # Create a new parameter entry with its return value
                        param_entry = {
                            "args": new_param_config.get("args", []),
                            "kwargs": new_param_config.get("kwargs", {}),
                            "return_value": feature_dict.get("return_value")
                        }
                        existing_api["parameters"].append(param_entry)

                        # Update description if provided
                        if "description" in feature_dict:
                            existing_api["description"] = feature_dict["description"]
                    else:
                        # No parameters in new patch, just update the API data
                        api_dict[sig_key] = feature_dict
                else:
                    # No existing parameters field, create new list format
                    if "parameters" in feature_dict:
                        new_param_config = feature_dict["parameters"]
                        param_entry = {
                            "args": new_param_config.get("args", []),
                            "kwargs": new_param_config.get("kwargs", {}),
                            "return_value": feature_dict.get("return_value")
                        }
                        api_dict[sig_key] = {
                            "description": feature_dict.get("description", "Auto-generated mock by LLM"),
                            "parameters": [param_entry]
                        }
                    else:
                        api_dict[sig_key] = feature_dict
            else:
                # New API entry - create with list format if parameters exist
                if "parameters" in feature_dict:
                    new_param_config = feature_dict["parameters"]
                    param_entry = {
                        "args": new_param_config.get("args", []),
                        "kwargs": new_param_config.get("kwargs", {}),
                        "return_value": feature_dict.get("return_value")
                    }
                    api_dict[sig_key] = {
                        "description": feature_dict.get("description", "Auto-generated mock by LLM"),
                        "parameters": [param_entry]
                    }
                else:
                    api_dict[sig_key] = feature_dict

    if "mocked_imports" in patch:
        for pkg_name, pkg_data in patch["mocked_imports"].items():
            pkg_entry = mock_state.setdefault("mocked_imports", {}).setdefault(pkg_name, {})
            if "api_features" in pkg_data:
                pkg_entry.setdefault("api_features", {}).update(pkg_data["api_features"])

    with open(STATE_FILE, "w") as f:
        json.dump(mock_state, f, indent=4, default=str)
    print(f"✅ Patch smartly routed and written to {STATE_FILE}.")

