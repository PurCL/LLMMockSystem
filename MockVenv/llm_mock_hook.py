class LLMMockProxyMeta(type):
    def __instancecheck__(cls, instance): return True
    def __subclasscheck__(cls, subclass): return True

class LLMMockProxy(metaclass=LLMMockProxyMeta):
    def __init__(self, name, *args, **kwargs):
        object.__setattr__(self, '_name', name)
        object.__setattr__(self, '__bases__', (object,))
        object.__setattr__(self, '__mro__', (self, object))

    def __mro_entries__(self, bases):
        def mock_init_subclass(cls, **kwargs): pass
        mock_base = type(self._name, (object,), {
            '__module__': '__main__',
            '__qualname__': self._name,
            '__init_subclass__': classmethod(mock_init_subclass),
        })
        return (mock_base,)

    def __getattr__(self, item):
        if item in ('_name', '__bases__', '__mro__'):
            return object.__getattribute__(self, item)
        if item in ('__path__', '__file__', '__spec__'):
            raise AttributeError(item)
        if item == '__name__':
            return self._name
        if item == '__class__':
            return type(self._name, (object,), {})

        full_path = f"{self._name}.{item}"
        sig_key = _get_logical_signature(full_path)

        # Look for explicit attribute mock (e.g., constants)
        mock_val = _track_and_get_mock(sig_key)
        if mock_val is not None:
            return mock_val

        if "Error" in item or "Exception" in item:
            class MockException(Exception): pass
            MockException.__name__ = item
            return MockException

        if item.startswith('__') and item.endswith('__'):
            raise AttributeError(item)

        # Return proxy to allow chaining (e.g., module.submodule.func())
        # The halt will happen in __call__ if the user actually invokes it.
        return LLMMockProxy(full_path)

    def __setattr__(self, name, value):
        if name in ('_name', '__bases__', '__mro__'):
            object.__setattr__(self, name, value)
        pass

